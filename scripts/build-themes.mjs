// Downloads color themes from tweakcn.com and writes:
//   app/color-themes.css            CSS variables per theme, light and dark
//   lib/color-themes.generated.ts   the theme list and swatch colors used by the navbar dropdown
// To add or remove a theme, edit THEMES and run `npm run themes`.
// Only colors and --radius are used; theme fonts and shadows are ignored.

import { readFileSync, writeFileSync } from "node:fs";
import { cssVarsIn } from "./css-vars.mjs";
import { oklchToHsl } from "./oklch-to-hsl.mjs";

const THEMES = [
  { id: "amethyst-haze", label: "Amethyst Haze" },
  { id: "caffeine", label: "Caffeine" },
  { id: "catppuccin", label: "Catppuccin" },
  { id: "claude", label: "Claude" },
  { id: "cyberpunk", label: "Cyberpunk" },
  { id: "mono", label: "Mono" },
  { id: "nature", label: "Nature" },
  { id: "ocean-breeze", label: "Ocean Breeze" },
  { id: "supabase", label: "Supabase" },
  { id: "t3-chat", label: "T3 Chat" },
  { id: "twitter", label: "Twitter" },
  { id: "vercel", label: "Vercel" },
];

// The color variables tailwind.config.ts reads.
const COLOR_VARS = [
  "background", "foreground", "card", "card-foreground", "popover", "popover-foreground",
  "primary", "primary-foreground", "secondary", "secondary-foreground", "muted",
  "muted-foreground", "accent", "accent-foreground", "destructive", "destructive-foreground",
  "border", "input", "ring", "chart-1", "chart-2", "chart-3", "chart-4", "chart-5",
];

// The colors shown as swatches next to each theme in the dropdown.
const SWATCH_VARS = ["background", "primary", "secondary", "accent"];

function hslVars(id, mode, vars) {
  return Object.fromEntries(
    COLOR_VARS.map((name) => {
      const value = vars?.[name];
      if (typeof value !== "string") throw new Error(`${id} (${mode}) is missing --${name}`);
      return [name, oklchToHsl(value)];
    }),
  );
}

function declarations(vars, radius) {
  const lines = COLOR_VARS.map((name) => `  --${name}: ${vars[name]};`);
  return [...lines, `  --radius: ${radius};`].join("\n");
}

function swatches(id, light, dark) {
  return SWATCH_VARS.map((name) => {
    if (!light[name] || !dark[name]) throw new Error(`${id} is missing --${name}`);
    return { light: light[name], dark: dark[name] };
  });
}

async function buildTheme({ id, label }) {
  const res = await fetch(`https://tweakcn.com/r/themes/${id}.json`);
  if (!res.ok) throw new Error(`${id}: HTTP ${res.status}`);
  const { cssVars } = await res.json();
  const radius = cssVars?.light?.radius ?? cssVars?.theme?.radius;
  if (typeof radius !== "string") throw new Error(`${id} is missing --radius`);

  const light = hslVars(id, "light", cssVars.light);
  const dark = hslVars(id, "dark", cssVars.dark);
  const css = [
    `:root[data-color-theme="${id}"] {\n${declarations(light, radius)}\n}`,
    `:root.dark[data-color-theme="${id}"] {\n${declarations(dark, radius)}\n}`,
  ].join("\n\n");
  return { css, theme: { id, label, swatches: swatches(id, light, dark) } };
}

const built = await Promise.all(THEMES.map(buildTheme));
const globals = readFileSync("app/globals.css", "utf8");
const defaultSwatches = swatches("default", cssVarsIn(globals, ":root"), cssVarsIn(globals, ".dark"));
const header = "Generated by scripts/build-themes.mjs from tweakcn.com. Do not edit by hand.";

writeFileSync("app/color-themes.css", `/* ${header} */\n\n${built.map((b) => b.css).join("\n\n")}\n`);
writeFileSync(
  "lib/color-themes.generated.ts",
  `// ${header}\n\n` +
    `// Swatches are "H S% L%" triplets: ${SWATCH_VARS.join(", ")}.\n` +
    `export const DEFAULT_SWATCHES = ${JSON.stringify(defaultSwatches, null, 2)} as const;\n\n` +
    `export const COLOR_THEMES = ${JSON.stringify(built.map((b) => b.theme), null, 2)} as const;\n`,
);
console.log(`Wrote ${THEMES.length} themes.`);
